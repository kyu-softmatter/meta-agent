#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""contracts/tools/cases.py -- what a condition tag means and what an index of a store holds
(plan.md 5.4, 14-27; meta_agent/tasks/006).

  python contracts/tools/cases.py index STORE_DIR     write STORE_DIR/index.json from the cards in it
  python contracts/tools/cases.py check STORE_DIR     say whether STORE_DIR/index.json is what the cards give

A store is a `cases/` or a `knowledge/` folder. Its index is generated, never written by hand: one row per
card (id, revision, path, sha256), sorted, with no time in it, so the same cards give the same file. A
reference on a card (`case_refs`, `kb_refs`) resolves in that index (check 5).

A condition tag is `name`, `name:value` or `name:lo..hi` with numbers lo <= hi (the unit goes in the name,
`shear_rate_1/s:1e-2..1e3`). Two tags of one name meet when they are equal, when a number lies in a range
or when two ranges overlap; recall (meta_agent/src/cases/) and check 8 read the same functions here, so
they cannot disagree about what a range is. Standard library only.
"""
import hashlib
import json
import os
import re
import sys

NUM = r"[-+]?[0-9]+(?:\.[0-9]+)?(?:[eE][-+]?[0-9]+)?"
TAG_RE = re.compile(r"^([A-Za-z][A-Za-z0-9_./%-]*)(?::(?:(" + NUM + r")\.\.(" + NUM + r")|((?:(?!\.\.)[A-Za-z0-9_.+-])+)))?$")
NUM_RE = re.compile(r"^" + NUM + r"$")
STORES = {
    "case_refs": {"dir": "cases", "card": "case", "key": "cases"},
    "kb_refs": {"dir": "knowledge", "card": "kb_entry", "key": "entries"},
}
GAPS = ("case_gaps", "kb_gaps")


def parse_tag(tag):
    """(name, kind, a, b): kind is 'name', 'value' (a: str), 'number' (a: float) or 'range' (a <= b floats).
    None when the tag is not one of the three forms; a reversed range parses with kind 'reversed'."""
    m = TAG_RE.match(tag) if isinstance(tag, str) else None
    if not m:
        return None
    name, lo, hi, value = m.groups()
    if lo is not None:
        a, b = float(lo), float(hi)
        return (name, "range" if a <= b else "reversed", a, b)
    if value is None:
        return (name, "name", None, None)
    if NUM_RE.match(value):
        return (name, "number", float(value), float(value))
    return (name, "value", value, None)


def tags_meet(x, y):
    """Do two condition tags speak of the same condition? Same name, and equal, contained or overlapping."""
    a, b = parse_tag(x), parse_tag(y)
    if not a or not b or a[0] != b[0] or "reversed" in (a[1], b[1]):
        return False
    numeric = ("number", "range")
    if a[1] in numeric and b[1] in numeric:
        return a[2] <= b[3] and b[2] <= a[3]
    return a[1:] == b[1:]


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return "sha256:" + h.hexdigest()


def rows_of(store_dir, card):
    """The index rows the cards in a store give, sorted by path."""
    rows = []
    base = os.path.dirname(os.path.abspath(store_dir))
    for root, dirs, files in os.walk(store_dir):
        dirs.sort()
        for name in sorted(files):
            if not name.endswith(".json") or name == "index.json":
                continue
            path = os.path.join(root, name)
            try:
                with open(path, "r", encoding="utf-8") as f:
                    data = json.load(f)
            except (ValueError, UnicodeDecodeError):
                continue
            if isinstance(data, dict) and data.get("card") == card and isinstance(data.get("id"), str):
                rows.append({"id": data["id"], "revision": data.get("revision"),
                             "path": os.path.relpath(path, base).replace(os.sep, "/"), "hash": sha256_of(path)})
    return sorted(rows, key=lambda r: r["path"])


def store_of(store_dir):
    name = os.path.basename(os.path.abspath(store_dir))
    for spec in STORES.values():
        if spec["dir"] == name:
            return spec
    return None


def build_index(store_dir):
    spec = store_of(store_dir)
    return {"schema_version": "0.1",
            "note": "Generated by `python contracts/tools/cases.py index <store>` from the cards in this store; never edited by hand. Check 5 compares it with the cards.",
            spec["key"]: rows_of(store_dir, spec["card"])}


def read_index(store_dir):
    path = os.path.join(store_dir, "index.json")
    if not os.path.isfile(path):
        return None
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except ValueError:
        return {}


def index_problem(store_dir):
    """None when index.json is what the cards give; otherwise what is wrong."""
    spec = store_of(store_dir)
    idx = read_index(store_dir)
    if idx is None:
        return "no index.json"
    if not isinstance(idx, dict) or idx.get(spec["key"]) != rows_of(store_dir, spec["card"]):
        return "index.json is not what the cards in the store give; regenerate it (python contracts/tools/cases.py index %s)" % spec["dir"]
    return None


def store_for(card_path, tree, dirname):
    """The nearest folder at or above a card, inside the tree, that holds a store of this name."""
    tree = os.path.abspath(tree)
    d = os.path.dirname(os.path.abspath(card_path))
    while True:
        cand = os.path.join(d, dirname)
        if os.path.isdir(cand):
            return cand
        if d == tree or os.path.dirname(d) == d:
            return None
        d = os.path.dirname(d)


def ref_problem(ref, store_dir, spec):
    """Why a reference does not resolve in a store's index (None when it does)."""
    idx = read_index(store_dir)
    rows = idx.get(spec["key"], []) if isinstance(idx, dict) else []
    hits = [r for r in rows if isinstance(r, dict) and r.get("id") == ref.get("id")]
    if not hits:
        return "id %r is not in %s/index.json" % (ref.get("id"), spec["dir"])
    if ref.get("version") is not None and not any(str(r.get("revision")) == str(ref["version"]) for r in hits):
        return "id %r has no revision %s in %s/index.json" % (ref.get("id"), ref["version"], spec["dir"])
    if ref.get("hash") is not None and not any(r.get("hash") == ref["hash"] for r in hits):
        return "id %r: the hash is not the indexed card's" % (ref.get("id"),)
    return None


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if len(argv) != 2 or argv[0] not in ("index", "check"):
        print(__doc__)
        return 2
    store_dir = argv[1]
    if not os.path.isdir(store_dir) or store_of(store_dir) is None:
        raise SystemExit("cases: %s is not a cases/ or knowledge/ folder" % store_dir)
    if argv[0] == "check":
        problem = index_problem(store_dir)
        print(problem or "index.json is what the cards give")
        return 1 if problem else 0
    idx = build_index(store_dir)
    with open(os.path.join(store_dir, "index.json"), "w", encoding="utf-8") as f:
        f.write(json.dumps(idx, indent=2, ensure_ascii=False) + "\n")
    print("written   %s/index.json (%d rows)" % (store_dir.rstrip("/"), len(idx[store_of(store_dir)["key"]])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
