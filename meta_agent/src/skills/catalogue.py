"""The catalogue: skills/index.json built from the manifests, and what a model reads to choose a skill.

The index is generated, never written by hand: the same manifests give the same file, byte for byte.
It carries no date and no seat. A skill whose folder, manifest or source check 22 would fault is not
indexed; building the index says why and stops.
"""
import os

from .. import cards
from . import LIBRARY, REPO, rules

INDEX_NAME = "index.json"
NOTE = ("Generated by `python -m meta_agent.src.skills index` from every skill.json under this folder; never "
        "edited by hand. A skill is taken by its ref, <id>@v<version>; sha256 is over the skill's folder.")


def skill_dirs(library=LIBRARY):
    """{ref: folder} for every skill of one library."""
    out = {}
    if os.path.isdir(library):
        for d in rules.find_skill_dirs(library):
            ref = os.path.basename(d)
            if ref in out:
                raise ValueError("%s is in the library twice: %s and %s" % (ref, out[ref], d))
            out[ref] = d
    return out


def find(ref, library=LIBRARY):
    return skill_dirs(library).get(ref)


def description_of(skill_dir):
    try:
        return rules.front_matter(cards.read_text(os.path.join(skill_dir, "SKILL.md"))).get("description", "")
    except OSError:
        return ""


def entry(skill_dir, library=LIBRARY, kinds=None):
    """One index row, read off the manifest. Raises ValueError when the folder or the source has a fault."""
    manifest = rules.read_manifest(skill_dir)
    kinds = kinds or rules.load_kinds()
    faults = rules.layout_problems(skill_dir, manifest, kinds)
    if manifest is not None and not faults:
        faults = rules.source_problems(skill_dir, manifest)
    if faults:
        raise ValueError("%s: %s" % (os.path.relpath(skill_dir, library).replace(os.sep, "/"), "; ".join(faults)))
    row = {
        "ref": "%s@v%d" % (manifest["id"], manifest["version"]),
        "id": manifest["id"],
        "version": manifest["version"],
        "kind": manifest["kind"],
        "side_effect": manifest["side_effect"],
        "status": manifest["status"],
        "summary": manifest["summary"],
        "description": description_of(skill_dir),
        "applies_to": manifest.get("applies_to", {}),
        "inputs": manifest.get("inputs", []),
        "outputs": manifest.get("outputs", []),
        "calls_tools": manifest.get("calls_tools", []),
        "uses_skills": manifest.get("uses_skills", []),
        "path": os.path.relpath(skill_dir, library).replace(os.sep, "/"),
        "sha256": cards.sha256_tree(skill_dir),
    }
    if "parameter" in manifest:
        row["parameter"] = manifest["parameter"]
        row["side"] = manifest.get("side")
    return row


def take(refs, library=LIBRARY):
    """The rows of the skills a specification names, in its order, each with the `folder` S5 copies from.
    Raises ValueError for a ref the library lacks."""
    dirs, kinds = skill_dirs(library), rules.load_kinds()
    missing = [r for r in refs if r not in dirs]
    if missing:
        raise ValueError("the library has no skill %s" % ", ".join(missing))
    return [dict(entry(dirs[r], library, kinds), folder=dirs[r]) for r in refs]


def build_index(library=LIBRARY):
    kinds = rules.load_kinds()
    rows = [entry(d, library, kinds) for _, d in sorted(skill_dirs(library).items())]
    rows.sort(key=lambda r: (r["kind"], r["id"], r["version"]))
    return {"schema_version": "0.1", "note": NOTE, "skills": rows}


def write_index(library=LIBRARY):
    path = os.path.join(library, INDEX_NAME)
    cards.write_json(path, build_index(library))
    return path


def index_is_current(library=LIBRARY):
    path = os.path.join(library, INDEX_NAME)
    return os.path.isfile(path) and cards.load_json(path) == build_index(library)


def select(rows, kind=None, parameter=None, instrument=None):
    out = []
    for r in rows:
        applies = r.get("applies_to") or {}
        if kind and r["kind"] != kind:
            continue
        if parameter and parameter not in set(applies.get("parameters") or []) | {r.get("parameter")}:
            continue
        if instrument and instrument not in (applies.get("instruments") or []):
            continue
        out.append(r)
    return out


def listing(rows):
    """What a model reads to choose: id and version, one line of what it gives, and its inputs."""
    lines = []
    for r in rows:
        ins = ", ".join("%s (%s)" % (i["name"], i["unit"]) for i in r["inputs"]) or "none"
        lines.append("%s  [%s, %s, %s]" % (r["ref"], r["kind"], r["side_effect"], r["status"]))
        lines.append("    %s" % r["summary"])
        lines.append("    inputs: %s" % ins)
    kinds = sorted({r["kind"] for r in rows})
    lines.append("%d skill(s) over %d kind(s)%s" % (len(rows), len(kinds), (": " + ", ".join(kinds)) if kinds else ""))
    return "\n".join(lines)


def rel_repo(path):
    return os.path.relpath(path, REPO).replace(os.sep, "/")
